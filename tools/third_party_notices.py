"""Writes THIRD-PARTY-NOTICES: the licence files of every Rust crate linked into the CORVID library,
copied verbatim from the crate sources that cargo resolved. Run before a release:

    python tools/third_party_notices.py
"""
import glob
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Compile-time only (procedural macros and build scripts): not part of the binary.
BUILD_ONLY = {"heck", "indoc", "proc-macro2", "pyo3-build-config", "pyo3-macros", "pyo3-macros-backend",
              "quote", "syn", "target-lexicon", "unicode-ident"}
# Same authors, same licence as CORVID (LICENSE).
OWN = {"sparta-solver", "scalpel"}


def main():
    meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT))
    tree = subprocess.check_output(["cargo", "tree", "-e", "normal", "--prefix", "none", "-f", "{p}"], cwd=ROOT, text=True)
    linked = {line.split()[0] for line in tree.splitlines() if line.strip()} - {"corvid"} - BUILD_ONLY
    pkgs = {p["name"]: p for p in meta["packages"] if p["name"] in linked}
    out = [
        "THIRD-PARTY NOTICES FOR CORVID",
        "==============================",
        "",
        "The CORVID library links the Rust crates below. Their licences require these notices to",
        "accompany binary distributions, so this file ships with every CORVID release. Generated by",
        "tools/third_party_notices.py from the crate sources cargo resolved; do not edit by hand.",
        "",
        "sparta-solver and scalpel (SPARTA, Copyright (C) 2026 Robert Fennis and Milan Rother) are",
        "licensed under the GNU AGPL, version 3 or later, like CORVID itself; see LICENSE.",
        "",
        "Crate                    Version     Licence",
        "-" * 80,
    ]
    for name in sorted(pkgs):
        p = pkgs[name]
        out.append(f"{name:<24} {p['version']:<11} {p.get('license') or '-'}")
    for name in sorted(pkgs):
        if name in OWN:
            continue
        p = pkgs[name]
        src = os.path.dirname(p["manifest_path"])
        files = sorted(f for f in glob.glob(os.path.join(src, "*")) if os.path.basename(f).upper().startswith(("LICENSE", "LICENCE", "COPYING", "UNLICENSE", "NOTICE")))
        out += ["", "", "=" * 80, f"{name} {p['version']}  ({p.get('license')})", "=" * 80]
        if not files:
            out.append(f"(no licence file in the crate source; licence declared in its Cargo.toml: {p.get('license')})")
        for f in files:
            out += ["", f"--- {os.path.basename(f)} ---", ""]
            out.append(open(f, encoding="utf-8", errors="replace").read().rstrip())
    open(os.path.join(ROOT, "THIRD-PARTY-NOTICES"), "w").write("\n".join(out) + "\n")
    print(f"THIRD-PARTY-NOTICES: {len(pkgs)} linked crates")


if __name__ == "__main__":
    main()
